#!/usr/bin/env python3
"""Generate every world-folder stub (.vsh/.fsh) from the table in programs.py.

Each stub is four lines: the #version line Iris requires first, the dimension, stage and
program macros (with values, so Iris's option scanner never treats them as options), and an
include of the shared body in shaders/program/. Run from anywhere:

    python3 tools/gen_stubs.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from programs import WORLDS, programs_for, program_macro  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent / "shaders"
HEADER = "#version 330 compatibility"


def stub(dim, stage, program, body):
    return "\n".join([
        HEADER,
        "// Generated by tools/gen_stubs.py. Edit shaders/program/%s.glsl instead." % body,
        "#define %s 1" % dim,
        "#define STAGE_%s 1" % stage,
        "#define %s 1" % program_macro(program),
        '#include "/program/%s.glsl"' % body,
        "",
    ])


def main():
    written = 0
    for world, dim in WORLDS.items():
        folder = ROOT / world
        folder.mkdir(parents=True, exist_ok=True)
        wanted = set()
        for program, body in sorted(programs_for(world).items()):
            for ext, stage in ((".vsh", "VERTEX"), (".fsh", "FRAGMENT")):
                path = folder / (program + ext)
                path.write_text(stub(dim, stage, program, body))
                wanted.add(path.name)
                written += 1
        # Remove stale stubs from programs that no longer exist.
        for path in folder.iterdir():
            if path.suffix in (".vsh", ".fsh", ".gsh", ".csh") and path.name not in wanted:
                path.unlink()
    print("wrote %d stubs" % written)


if __name__ == "__main__":
    main()
